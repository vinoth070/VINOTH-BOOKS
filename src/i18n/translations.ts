// Returns translation value or falls back to English, then defaultVal, then key
export function getTranslation(lang: string, key: string, defaultVal?: string): string {
  // Check direct bundle
  if (TRANSLATIONS[lang] && (TRANSLATIONS[lang] as any)[key]) {
    return (TRANSLATIONS[lang] as any)[key];
  }
  // Check language override map
  if (LANGUAGE_NAME_MAP[lang] && (LANGUAGE_NAME_MAP[lang] as any)[key]) {
    return (LANGUAGE_NAME_MAP[lang] as any)[key]!;
  }
  // Fallback to English
  if (TRANSLATIONS.en && (TRANSLATIONS.en as any)[key]) {
    return (TRANSLATIONS.en as any)[key];
  }
  return defaultVal || key;
}
